// Release signing reads from local.properties (dev machines) with an env-var fallback (future CI).
// Never commit a keystore or its passwords — see README for keystore creation steps.
val keystoreProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) load(FileInputStream(f))
}
fun signingProp(key: String): String? = keystoreProps.getProperty(key) ?: System.getenv(key)

